-- ---------------------------------------------------------------------
-- 1. USUÁRIOS E AUTENTICAÇÃO  (UC03, UC04, UC07, UC10, UC11)
-- ---------------------------------------------------------------------

CREATE TABLE usuario (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf                     VARCHAR(11),                 -- só dígitos; NULL apenas p/ ADMIN ou conta EXCLUIDA
    nome                    VARCHAR(150) NOT NULL,
    data_nascimento         DATE         NOT NULL,       -- base da regra 18+ (I10), inclusive no login social (I19)
    genero                  VARCHAR(10),                 -- NULL em conta criada via login social (I19)
    celular                 VARCHAR(11),                 -- DDD + 9 dígitos (RN03); NULL em conta social
    email                   VARCHAR(254) NOT NULL,
    senha_hash              VARCHAR(100),                -- NULL em conta social sem senha (UC07-A4)
    perfil                  VARCHAR(10)  NOT NULL DEFAULT 'CLIENTE',
    status                  VARCHAR(10)  NOT NULL DEFAULT 'PENDENTE',
    termos_versao           VARCHAR(20)  NOT NULL,       -- I8: prova de aceite (LGPD)
    termos_aceitos_em       TIMESTAMPTZ  NOT NULL,
    tentativas_login_falhas INTEGER      NOT NULL DEFAULT 0,   -- UC10-E2 (bloqueio temporário)
    bloqueado_ate           TIMESTAMPTZ,
    criado_em               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    excluido_em             TIMESTAMPTZ,                 -- I14: "excluir minha conta" = anonimização

    CONSTRAINT uq_usuario_cpf            UNIQUE (cpf),   -- RN01 (NULLs múltiplos são permitidos)
    CONSTRAINT ck_usuario_cpf_formato    CHECK (cpf IS NULL OR cpf ~ '^[0-9]{11}$'),
    CONSTRAINT ck_usuario_cpf_obrig      CHECK (cpf IS NOT NULL OR perfil = 'ADMIN' OR status = 'EXCLUIDA'),
    CONSTRAINT ck_usuario_genero         CHECK (genero IS NULL OR genero IN ('MASCULINO', 'FEMININO')),
    CONSTRAINT ck_usuario_celular        CHECK (celular IS NULL OR celular ~ '^[0-9]{11}$'),
    CONSTRAINT ck_usuario_perfil         CHECK (perfil IN ('CLIENTE', 'ADMIN')),
    CONSTRAINT ck_usuario_status         CHECK (status IN ('PENDENTE', 'ATIVA', 'EXCLUIDA')),
    CONSTRAINT ck_usuario_admin_senha    CHECK (perfil <> 'ADMIN' OR senha_hash IS NOT NULL),  -- I17: admin só usa senha
    CONSTRAINT ck_usuario_exclusao       CHECK ((status = 'EXCLUIDA') = (excluido_em IS NOT NULL)),
    CONSTRAINT ck_usuario_tentativas     CHECK (tentativas_login_falhas >= 0)
);
-- RN02: e-mail único, sem diferenciar maiúsculas/minúsculas.
CREATE UNIQUE INDEX ux_usuario_email ON usuario (lower(email));


-- Vínculo conta Google/Facebook <-> usuário (UC10-A1/A2)
CREATE TABLE identidade_social (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id          BIGINT       NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    provedor            VARCHAR(10)  NOT NULL,
    provedor_usuario_id VARCHAR(100) NOT NULL,           -- "sub" devolvido pelo provedor
    criado_em           TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_identidade_provedor      CHECK (provedor IN ('GOOGLE', 'FACEBOOK')),
    CONSTRAINT uq_identidade_conta         UNIQUE (provedor, provedor_usuario_id),
    CONSTRAINT uq_identidade_usuario_prov  UNIQUE (usuario_id, provedor)   -- UC10-E5
);


-- Códigos de 6 dígitos: confirmar conta, trocar e-mail/celular (I14),
-- recuperar senha e confirmar identidade no vínculo social (I19).
-- Cada (re)envio cria uma linha; o reenvio invalida a anterior (UC04-A1).
CREATE TABLE codigo_verificacao (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT       NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    finalidade    VARCHAR(20)  NOT NULL,
    canal         VARCHAR(5)   NOT NULL,
    destino       VARCHAR(254) NOT NULL,                 -- contato completo (novo e-mail/celular); nunca exibir inteiro
    codigo_hash   VARCHAR(100) NOT NULL,                 -- guarde o hash, não o código
    tentativas    INTEGER      NOT NULL DEFAULT 0,       -- UC04-E1: máx. 5
    expira_em     TIMESTAMPTZ  NOT NULL,                 -- 10 min
    usado_em      TIMESTAMPTZ,                           -- uso único
    invalidado_em TIMESTAMPTZ,
    criado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_codigo_finalidade CHECK (finalidade IN
        ('CADASTRO', 'ALTERAR_EMAIL', 'ALTERAR_CELULAR', 'RECUPERAR_SENHA', 'VINCULO_SOCIAL')),
    CONSTRAINT ck_codigo_canal      CHECK (canal IN ('EMAIL', 'SMS')),
    CONSTRAINT ck_codigo_tentativas CHECK (tentativas >= 0)
);
CREATE INDEX ix_codigo_verificacao_busca ON codigo_verificacao (usuario_id, finalidade, criado_em DESC);


-- ---------------------------------------------------------------------
-- 2. CATÁLOGO  (UC01, UC02, UC12, UC13)
-- ---------------------------------------------------------------------

CREATE TABLE categoria (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(80)  NOT NULL,
    descricao        TEXT,
    categoria_pai_id BIGINT       REFERENCES categoria (id),  -- hierarquia (ciclos: validar na aplicação, UC13-E3)
    imagem           VARCHAR(255),
    ordem            INTEGER      NOT NULL DEFAULT 0,
    ativa            BOOLEAN      NOT NULL DEFAULT TRUE,
    exige_receita    BOOLEAN      NOT NULL DEFAULT FALSE,     -- "Controlados": herdada pelos produtos (UC13)
    criado_em        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_categoria_pai CHECK (categoria_pai_id IS NULL OR categoria_pai_id <> id)
);
-- UC13: nome único dentro da mesma categoria pai.
CREATE UNIQUE INDEX ux_categoria_nome_pai ON categoria (COALESCE(categoria_pai_id, 0), lower(nome));
CREATE INDEX ix_categoria_pai ON categoria (categoria_pai_id);


-- Nome completo exibido no UC02 = produto.nome + ' ' + apresentacao.descricao
-- (ex.: "Novalgina Dipirona 1g" + "20 comprimidos").
CREATE TABLE produto (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome               VARCHAR(200) NOT NULL,
    marca              VARCHAR(100) NOT NULL,
    principio_ativo    VARCHAR(150),
    tipo               VARCHAR(10),                       -- NULL p/ itens que não são medicamento
    forma_farmaceutica VARCHAR(30),                       -- comprimido, xarope, gotas, pomada...
    tarja              VARCHAR(10)  NOT NULL DEFAULT 'SEM_TARJA',
    exige_receita      BOOLEAN      NOT NULL DEFAULT FALSE,   -- I3: TRUE => pedido só pode ser RETIRADA
    registro_ms        VARCHAR(30),                       -- registro no Ministério da Saúde
    bula_url           VARCHAR(255),
    indicacao          TEXT,                              -- descrição em tópicos (UC02)
    acao               TEXT,
    via_administracao  TEXT,
    publico_alvo       TEXT,
    ativo              BOOLEAN      NOT NULL DEFAULT TRUE,    -- exclusão lógica (UC12)
    visualizacoes      BIGINT       NOT NULL DEFAULT 0,       -- "Mais vistos" da home
    qtd_vendida        BIGINT       NOT NULL DEFAULT 0,       -- "Mais comprados" / ordenar por mais vendidos
    criado_em          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_por_id  BIGINT       REFERENCES usuario (id),  -- UC12: "registra quem alterou e quando"

    CONSTRAINT ck_produto_tipo    CHECK (tipo IS NULL OR tipo IN ('GENERICO', 'SIMILAR', 'REFERENCIA')),
    CONSTRAINT ck_produto_tarja   CHECK (tarja IN ('SEM_TARJA', 'VERMELHA', 'PRETA')),
    CONSTRAINT ck_produto_receita CHECK (tarja = 'SEM_TARJA' OR exige_receita),   -- regra do UC12
    CONSTRAINT ck_produto_contadores CHECK (visualizacoes >= 0 AND qtd_vendida >= 0)
);

CREATE TABLE produto_categoria (
    produto_id   BIGINT NOT NULL REFERENCES produto (id)   ON DELETE CASCADE,
    categoria_id BIGINT NOT NULL REFERENCES categoria (id),
    PRIMARY KEY (produto_id, categoria_id)
);
CREATE INDEX ix_produto_categoria_categoria ON produto_categoria (categoria_id);


-- A "apresentação" é a unidade de venda (10, 20 ou 30 comprimidos).
-- Preço, SKU, EAN e estoque ficam aqui, não no produto (UC02, UC12).
CREATE TABLE apresentacao (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id        BIGINT        NOT NULL REFERENCES produto (id) ON DELETE CASCADE,
    descricao         VARCHAR(60)   NOT NULL,             -- ex.: "20 comprimidos"
    sku               VARCHAR(40)   NOT NULL,
    ean               VARCHAR(14)   NOT NULL,
    preco             NUMERIC(10,2) NOT NULL,             -- por unidade da apresentação
    estoque           INTEGER       NOT NULL DEFAULT 0,
    limite_por_pedido INTEGER       NOT NULL DEFAULT 10,  -- I5: limite de unidades por item
    ordem             INTEGER       NOT NULL DEFAULT 0,   -- a de menor ordem é a padrão
    ativa             BOOLEAN       NOT NULL DEFAULT TRUE,
    versao            BIGINT        NOT NULL DEFAULT 0,   -- @Version: lock otimista do estoque
    criado_em         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em     TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT uq_apresentacao_sku    UNIQUE (sku),       -- UC12-E1
    CONSTRAINT uq_apresentacao_ean    UNIQUE (ean),
    CONSTRAINT ck_apresentacao_ean    CHECK (ean ~ '^[0-9]{8,14}$'),
    CONSTRAINT ck_apresentacao_preco  CHECK (preco > 0),
    CONSTRAINT ck_apresentacao_estoque CHECK (estoque >= 0),
    CONSTRAINT ck_apresentacao_limite CHECK (limite_por_pedido > 0)
);
CREATE INDEX ix_apresentacao_produto ON apresentacao (produto_id, ordem);

-- apresentacao_id NULL = imagem vale para todas as apresentações do produto.
-- Com valor, a imagem troca ao selecionar a apresentação (UC02-A1).
CREATE TABLE imagem_produto (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id      BIGINT       NOT NULL REFERENCES produto (id) ON DELETE CASCADE,
    apresentacao_id BIGINT       REFERENCES apresentacao (id) ON DELETE CASCADE,
    arquivo         VARCHAR(255) NOT NULL,
    ordem           INTEGER      NOT NULL DEFAULT 0,
    criado_em       TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_imagem_produto_produto ON imagem_produto (produto_id, ordem);


-- ---------------------------------------------------------------------
-- 3. CARRINHO  (UC05)  — I12: visitante salvo e mesclado ao logar
-- ---------------------------------------------------------------------
-- Dono = usuário OU token (UUID guardado em cookie do visitante). Nunca os dois.
-- No login (UC10), os itens do carrinho do token são mesclados ao do usuário
-- e o carrinho do token é apagado.

CREATE TABLE carrinho (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT      REFERENCES usuario (id) ON DELETE CASCADE,
    token         UUID,
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uq_carrinho_usuario UNIQUE (usuario_id),
    CONSTRAINT uq_carrinho_token   UNIQUE (token),
    CONSTRAINT ck_carrinho_dono    CHECK ((usuario_id IS NULL) <> (token IS NULL))
);

CREATE TABLE item_carrinho (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrinho_id     BIGINT        NOT NULL REFERENCES carrinho (id)     ON DELETE CASCADE,
    apresentacao_id BIGINT        NOT NULL REFERENCES apresentacao (id) ON DELETE CASCADE,
    quantidade      INTEGER       NOT NULL,
    preco_visto     NUMERIC(10,2) NOT NULL,                -- preço quando foi adicionado: detecta UC05-E3
    criado_em       TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT uq_item_carrinho UNIQUE (carrinho_id, apresentacao_id),   -- UC05: se já existe, soma
    CONSTRAINT ck_item_carrinho_qtd CHECK (quantidade > 0)
);
CREATE INDEX ix_item_carrinho_apresentacao ON item_carrinho (apresentacao_id);


-- ---------------------------------------------------------------------
-- 4. ENDEREÇOS, CARTÕES, LOJAS  (UC09)
-- ---------------------------------------------------------------------

CREATE TABLE endereco (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT       NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    destinatario  VARCHAR(150) NOT NULL,
    cep           VARCHAR(8)   NOT NULL,
    logradouro    VARCHAR(200) NOT NULL,
    numero        VARCHAR(20)  NOT NULL,
    complemento   VARCHAR(100),
    bairro        VARCHAR(100) NOT NULL,
    cidade        VARCHAR(100) NOT NULL,
    uf            VARCHAR(2)   NOT NULL,
    referencia    VARCHAR(200),
    criado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_endereco_cep CHECK (cep ~ '^[0-9]{8}$')
);
CREATE INDEX ix_endereco_usuario ON endereco (usuario_id);

-- I16: só token do gateway + dados mascarados. NUNCA número completo nem CVV.
CREATE TABLE cartao_salvo (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT       NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    token_gateway  VARCHAR(100) NOT NULL,
    bandeira       VARCHAR(20)  NOT NULL,
    ultimos4       VARCHAR(4)   NOT NULL,
    validade_mes   INTEGER      NOT NULL,
    validade_ano   INTEGER      NOT NULL,
    nome_impresso  VARCHAR(100) NOT NULL,
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_cartao_token    UNIQUE (usuario_id, token_gateway),
    CONSTRAINT ck_cartao_ultimos4 CHECK (ultimos4 ~ '^[0-9]{4}$'),
    CONSTRAINT ck_cartao_validade CHECK (validade_mes BETWEEN 1 AND 12 AND validade_ano >= 2000)
);
CREATE INDEX ix_cartao_salvo_usuario ON cartao_salvo (usuario_id);

-- I3: lojas para retirada de pedidos com item que exige receita.
CREATE TABLE loja (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(100) NOT NULL,
    cep                   VARCHAR(8)   NOT NULL,
    logradouro            VARCHAR(200) NOT NULL,
    numero                VARCHAR(20)  NOT NULL,
    bairro                VARCHAR(100) NOT NULL,
    cidade                VARCHAR(100) NOT NULL,
    uf                    VARCHAR(2)   NOT NULL,
    horario_funcionamento VARCHAR(200),
    ativa                 BOOLEAN      NOT NULL DEFAULT TRUE,

    CONSTRAINT ck_loja_cep CHECK (cep ~ '^[0-9]{8}$')
);


-- ---------------------------------------------------------------------
-- 5. PEDIDOS E PAGAMENTOS  (UC06, UC08)
-- ---------------------------------------------------------------------
-- O endereço de entrega é COPIADO para o pedido (snapshot): editar ou
-- excluir um endereço salvo não altera pedidos antigos.
-- Regra que o banco não consegue garantir (cruza tabelas) e o service deve:
-- se algum item_pedido.exige_receita = TRUE  =>  tipo_entrega = 'RETIRADA'.

CREATE TABLE pedido (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- é o "número do pedido"
    usuario_id            BIGINT        NOT NULL REFERENCES usuario (id),
    status                VARCHAR(25)   NOT NULL DEFAULT 'AGUARDANDO_PAGAMENTO',  -- I13
    tipo_entrega          VARCHAR(10)   NOT NULL,
    loja_retirada_id      BIGINT        REFERENCES loja (id),
    entrega_destinatario  VARCHAR(150),
    entrega_cep           VARCHAR(8),
    entrega_logradouro    VARCHAR(200),
    entrega_numero        VARCHAR(20),
    entrega_complemento   VARCHAR(100),
    entrega_bairro        VARCHAR(100),
    entrega_cidade        VARCHAR(100),
    entrega_uf            VARCHAR(2),
    entrega_referencia    VARCHAR(200),
    prazo_entrega_dias    INTEGER,
    subtotal              NUMERIC(10,2) NOT NULL,
    frete                 NUMERIC(10,2) NOT NULL DEFAULT 0,
    total                 NUMERIC(10,2) NOT NULL,
    expira_em             TIMESTAMPTZ,                    -- Pix/boleto aguardando pagamento (UC08-A2)
    criado_em             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em         TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT ck_pedido_status CHECK (status IN
        ('AGUARDANDO_PAGAMENTO', 'PAGAMENTO_APROVADO', 'EM_SEPARACAO', 'ENVIADO', 'PRONTO_PARA_RETIRADA', 'ENTREGUE', 'CANCELADO')),
    CONSTRAINT ck_pedido_tipo_entrega CHECK (tipo_entrega IN ('ENTREGA', 'RETIRADA')),
    CONSTRAINT ck_pedido_valores CHECK (subtotal >= 0 AND frete >= 0 AND total = subtotal + frete),
    CONSTRAINT ck_pedido_entrega CHECK (
        (tipo_entrega = 'ENTREGA'
            AND loja_retirada_id IS NULL
            AND entrega_destinatario IS NOT NULL AND entrega_cep    IS NOT NULL
            AND entrega_logradouro   IS NOT NULL AND entrega_numero IS NOT NULL
            AND entrega_bairro       IS NOT NULL AND entrega_cidade IS NOT NULL
            AND entrega_uf           IS NOT NULL)
        OR
        (tipo_entrega = 'RETIRADA'
            AND loja_retirada_id IS NOT NULL
            AND frete = 0)
    )
);
CREATE INDEX ix_pedido_usuario ON pedido (usuario_id, criado_em DESC);
CREATE INDEX ix_pedido_status  ON pedido (status);

-- Snapshot do item: nome, descrição e preço NO MOMENTO da compra (UC06).
-- apresentacao_id sem CASCADE: produto com pedidos não pode ser excluído de vez (UC12-E4).
CREATE TABLE item_pedido (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id              BIGINT        NOT NULL REFERENCES pedido (id) ON DELETE CASCADE,
    apresentacao_id        BIGINT        NOT NULL REFERENCES apresentacao (id),
    nome_produto           VARCHAR(200)  NOT NULL,
    descricao_apresentacao VARCHAR(60)   NOT NULL,
    sku                    VARCHAR(40)   NOT NULL,
    preco_unitario         NUMERIC(10,2) NOT NULL,
    quantidade             INTEGER       NOT NULL,
    exige_receita          BOOLEAN       NOT NULL DEFAULT FALSE,

    CONSTRAINT ck_item_pedido_preco CHECK (preco_unitario > 0),
    CONSTRAINT ck_item_pedido_qtd   CHECK (quantidade > 0)
);
CREATE INDEX ix_item_pedido_pedido      ON item_pedido (pedido_id);
CREATE INDEX ix_item_pedido_apresentacao ON item_pedido (apresentacao_id);

-- Um pedido pode ter várias tentativas (UC08-E2: recusado -> outro método).
-- Do cartão guardamos só dados mascarados (UC06 exibe "método mascarado").
CREATE TABLE pagamento (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id            BIGINT        NOT NULL REFERENCES pedido (id) ON DELETE CASCADE,
    metodo               VARCHAR(15)   NOT NULL,
    status               VARCHAR(10)   NOT NULL DEFAULT 'PENDENTE',
    valor                NUMERIC(10,2) NOT NULL,
    parcelas             INTEGER       NOT NULL DEFAULT 1,
    transacao_gateway_id VARCHAR(100),
    cartao_bandeira      VARCHAR(20),
    cartao_ultimos4      VARCHAR(4),
    cartao_salvo_id      BIGINT        REFERENCES cartao_salvo (id) ON DELETE SET NULL,
    codigo_pagamento     TEXT,                              -- Pix copia-e-cola ou linha digitável do boleto
    expira_em            TIMESTAMPTZ,
    criado_em            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em        TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT ck_pagamento_metodo   CHECK (metodo IN ('CARTAO_CREDITO', 'CARTAO_DEBITO', 'PIX', 'BOLETO')),
    CONSTRAINT ck_pagamento_status   CHECK (status IN ('PENDENTE', 'APROVADO', 'RECUSADO', 'EXPIRADO')),
    CONSTRAINT ck_pagamento_valor    CHECK (valor > 0),
    CONSTRAINT ck_pagamento_parcelas CHECK (parcelas >= 1 AND (parcelas = 1 OR metodo = 'CARTAO_CREDITO'))
);
CREATE INDEX ix_pagamento_pedido ON pagamento (pedido_id);

CREATE TABLE historico_status_pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT       NOT NULL REFERENCES pedido (id) ON DELETE CASCADE,
    status          VARCHAR(25)  NOT NULL,
    alterado_por_id BIGINT       REFERENCES usuario (id),   -- NULL = sistema (ex.: pagamento aprovado pelo gateway)
    observacao      VARCHAR(255),
    criado_em       TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_historico_status CHECK (status IN
        ('AGUARDANDO_PAGAMENTO', 'PAGAMENTO_APROVADO', 'EM_SEPARACAO', 'ENVIADO', 'PRONTO_PARA_RETIRADA', 'ENTREGUE', 'CANCELADO'))
);
CREATE INDEX ix_historico_pedido ON historico_status_pedido (pedido_id, criado_em);


-- ---------------------------------------------------------------------
-- 6. AUDITORIA  (UC11 / LGPD)
-- ---------------------------------------------------------------------
-- Registra cada acesso do administrador a dados de clientes.

CREATE TABLE log_auditoria (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT       REFERENCES usuario (id),         -- quem acessou
    acao       VARCHAR(40)  NOT NULL,                        -- ex.: CLIENTE_LISTAR, CLIENTE_VISUALIZAR, CLIENTE_EXPORTAR
    alvo_tipo  VARCHAR(30),
    alvo_id    BIGINT,
    detalhes   VARCHAR(500),                                 -- filtros usados, etc.
    ip         VARCHAR(45),
    criado_em  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_log_auditoria_data    ON log_auditoria (criado_em DESC);
CREATE INDEX ix_log_auditoria_usuario ON log_auditoria (usuario_id);
